#nullable enable

using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;

namespace Kesmai.WorldForge.Editor.Quests;

/// <summary>
/// Turns a <see cref="QuestDefinition"/> into a segment source file: a static quest class that keeps each player's
/// stage and progress in <c>Storage</c>, a <c>Questkeeper</c> that offers the stage choices as interactions, and an
/// escort follower when the quest has escort stages. Kill stages count through a line added to the target entity's
/// OnDeath script (see <see cref="KillHook"/>).
/// </summary>
public static class QuestCodeGenerator
{
	/// <summary>The line a kill target's OnDeath script needs so its deaths count for the quest.</summary>
	public static string KillHook(QuestDefinition quest, string entityName)
		=> $"{quest.Name}Quest.OnKilled({Literal(entityName)}, source, killer);";

	/// <summary>Problems that would stop the quest from working, in plain words. Empty when the quest is ready.</summary>
	public static List<string> Validate(QuestDefinition quest)
	{
		var problems = new List<string>();
		var ids = quest.Stages.Select(s => s.Id).ToList();

		if (!QuestDefinition.IsIdentifier(quest.Name))
			problems.Add($"The quest name \"{quest.Name}\" must be letters, digits and underscores, starting with a letter.");

		if (quest.Stages.Count == 0)
			problems.Add("Add at least one stage.");
		else if (!ids.Contains(quest.StartStage))
			problems.Add($"The first stage \"{quest.StartStage}\" doesn't exist.");

		foreach (var duplicate in ids.GroupBy(i => i).Where(g => g.Count() > 1))
			problems.Add($"Two stages are called \"{duplicate.Key}\".");

		foreach (var stage in quest.Stages)
		{
			if (!QuestDefinition.IsIdentifier(stage.Id))
				problems.Add($"Stage \"{stage.Id}\": the name must be letters, digits and underscores.");

			if (stage.Kind is QuestStageKind.Kill or QuestStageKind.Collect)
			{
				if (!QuestDefinition.IsIdentifier(stage.Target))
					problems.Add($"Stage \"{stage.Id}\": pick {(stage.Kind == QuestStageKind.Kill ? "a creature entity" : "an item type")}.");

				if (stage.Count < 1)
					problems.Add($"Stage \"{stage.Id}\": the count must be at least 1.");
			}

			if (stage.Kind != QuestStageKind.End && stage.Choices.Count == 0)
				problems.Add($"Stage \"{stage.Id}\": add a choice, or make it an End stage, so the player can move on.");

			foreach (var choice in stage.Choices.Where(c => !ids.Contains(c.Next)))
				problems.Add($"Stage \"{stage.Id}\": the choice \"{choice.Label}\" leads to \"{choice.Next}\", which doesn't exist.");
		}

		if (!quest.Stages.Any(s => s.Kind == QuestStageKind.End))
			problems.Add("Add an End stage so the quest can be completed.");

		return problems;
	}

	/// <summary>Stages no path from the first stage reaches. Not an error, but usually a mistake.</summary>
	public static List<string> Unreachable(QuestDefinition quest)
	{
		var reached = new HashSet<string>();
		var pending = new Stack<string>();

		pending.Push(quest.StartStage);

		while (pending.Count > 0)
		{
			var id = pending.Pop();

			if (!reached.Add(id))
				continue;

			foreach (var choice in quest.Stages.Where(s => s.Id == id).SelectMany(s => s.Choices))
				pending.Push(choice.Next);
		}

		return quest.Stages.Select(s => s.Id).Where(id => !reached.Contains(id)).ToList();
	}

	public static string Generate(QuestDefinition quest, string segmentName)
	{
		var q = quest.Name;
		var b = new StringBuilder();

		b.AppendLine("// <auto-generated>");
		b.AppendLine("// Made with the WorldForge Quest Maker. Edit the quest there: saving it again replaces this file.");
		b.AppendLine("// </auto-generated>");
		b.AppendLine(quest.ToMarkerLine());
		b.AppendLine();
		b.AppendLine("using DotNext.Buffers;");
		b.AppendLine("using Kesmai.Server.Engines.Interactions;");
		b.AppendLine("using Kesmai.Server.Game;");
		b.AppendLine("using Kesmai.Server.Items;");
		b.AppendLine("using Kesmai.Server.Miscellaneous;");
		b.AppendLine("using System;");
		b.AppendLine("using System.Collections.Generic;");
		b.AppendLine("using System.Drawing;");
		b.AppendLine("using System.Linq;");
		b.AppendLine("using SpanReader = DotNext.Buffers.SpanReader<byte>;");
		b.AppendLine("using SpanWriter = DotNext.Buffers.PoolingArrayBufferWriter<byte>;");
		b.AppendLine();
		b.AppendLine($"namespace Kesmai.Server.Internal.{segmentName};");
		b.AppendLine();
		b.AppendLine("public partial class Cache");
		b.AppendLine("{");

		GenerateQuestClass(b, quest, segmentName);
		b.AppendLine();
		GenerateGiver(b, quest);

		if (quest.Stages.Any(s => s.Kind == QuestStageKind.Escort))
		{
			b.AppendLine();
			GenerateEscort(b, quest);
		}

		b.AppendLine("}");

		return b.ToString();
	}

	private static void GenerateQuestClass(StringBuilder b, QuestDefinition quest, string segmentName)
	{
		var q = quest.Name;
		var stages = quest.Stages.ToList();

		b.AppendLine($"\t/// <summary>{Xml(quest.Title)}. Each player's stage and progress are kept in Storage.</summary>");
		b.AppendLine($"\tpublic static class {q}Quest");
		b.AppendLine("\t{");
		b.AppendLine($"\t\tpublic const string Title = {Literal(quest.Title)};");
		b.AppendLine($"\t\tprivate const string Key = {Literal($"Segment:{segmentName}:Quest:{q}")};");
		b.AppendLine("\t\tpublic const string NotStarted = \"\";");
		b.AppendLine("\t\tpublic const string Completed = \"#completed\";");
		b.AppendLine();
		b.AppendLine("\t\tpublic static string GetStage(PlayerEntity player) => Storage.Get(player).Get<string>(Key + \":Stage\", NotStarted) ?? NotStarted;");
		b.AppendLine("\t\tpublic static int GetProgress(PlayerEntity player) => Storage.Get(player).Get<int>(Key + \":Progress\", 0);");
		b.AppendLine("\t\tprivate static void SetStage(PlayerEntity player, string stage) => Storage.Get(player).Set<string>(Key + \":Stage\", stage);");
		b.AppendLine("\t\tprivate static void SetProgress(PlayerEntity player, int value) => Storage.Get(player).Set<int>(Key + \":Progress\", value);");
		b.AppendLine("\t\tpublic static bool IsComplete(PlayerEntity player) => GetStage(player) == Completed;");
		b.AppendLine();

		// Talk
		b.AppendLine("\t\t/// <summary>The giver tells the player where they stand.</summary>");
		b.AppendLine("\t\tpublic static void Talk(PlayerEntity player, MobileEntity giver)");
		b.AppendLine("\t\t{");
		b.AppendLine("\t\t\tvar stage = GetStage(player);");
		b.AppendLine();
		b.AppendLine("\t\t\tswitch (stage)");
		b.AppendLine("\t\t\t{");
		b.AppendLine($"\t\t\t\tcase NotStarted: giver.SayTo(player, {Literal(quest.Intro)}); return;");
		b.AppendLine($"\t\t\t\tcase Completed: giver.SayTo(player, {Literal(quest.CompletedText)}); return;");

		foreach (var stage in stages.Where(s => s.Kind is QuestStageKind.Kill or QuestStageKind.Collect or QuestStageKind.Escort))
		{
			b.AppendLine($"\t\t\t\tcase {Literal(stage.Id)}:");

			if (stage.Kind == QuestStageKind.Escort)
				b.AppendLine($"\t\t\t\t\tif (!IsObjectiveDone(player, stage)) SummonEscort(player, giver, stage);");

			var progress = stage.Kind switch
			{
				QuestStageKind.Kill => $"$\"{Interpolated(stage.Text)} ({{GetProgress(player)}}/{stage.Count} {Interpolated(stage.Target)})\"",
				QuestStageKind.Collect => $"$\"{Interpolated(stage.Text)} ({{Math.Min(CountCarried<{stage.Target}>(player), {stage.Count})}}/{stage.Count})\"",
				_ => Literal(stage.Text),
			};

			b.AppendLine($"\t\t\t\t\tgiver.SayTo(player, IsObjectiveDone(player, stage) ? {Literal(DoneOrDefault(stage))} : {progress});");
			b.AppendLine("\t\t\t\t\treturn;");
		}

		b.AppendLine("\t\t\t}");
		b.AppendLine();
		b.AppendLine("\t\t\tgiver.SayTo(player, GetText(stage));");
		b.AppendLine("\t\t}");
		b.AppendLine();

		// GetText
		b.AppendLine("\t\tprivate static string GetText(string stage)");
		b.AppendLine("\t\t{");
		b.AppendLine("\t\t\tswitch (stage)");
		b.AppendLine("\t\t\t{");
		foreach (var stage in stages)
			b.AppendLine($"\t\t\t\tcase {Literal(stage.Id)}: return {Literal(stage.Text)};");
		b.AppendLine("\t\t\t\tdefault: return String.Empty;");
		b.AppendLine("\t\t\t}");
		b.AppendLine("\t\t}");
		b.AppendLine();

		// GetChoices
		b.AppendLine("\t\t/// <summary>The choices the giver offers right now: accepting the quest, or the current stage's choices once its objective is done.</summary>");
		b.AppendLine("\t\tpublic static List<KeyValuePair<string, string>> GetChoices(PlayerEntity player)");
		b.AppendLine("\t\t{");
		b.AppendLine("\t\t\tvar stage = GetStage(player);");
		b.AppendLine("\t\t\tvar choices = new List<KeyValuePair<string, string>>();");
		b.AppendLine();
		b.AppendLine($"\t\t\tif (stage == NotStarted{(quest.Repeatable ? " || stage == Completed" : String.Empty)})");
		b.AppendLine($"\t\t\t\tchoices.Add(new KeyValuePair<string, string>({Literal(quest.AcceptLabel)}, {Literal(quest.StartStage)}));");
		b.AppendLine();
		b.AppendLine("\t\t\tif (stage == NotStarted || stage == Completed || !IsObjectiveDone(player, stage))");
		b.AppendLine("\t\t\t\treturn choices;");
		b.AppendLine();
		b.AppendLine("\t\t\tswitch (stage)");
		b.AppendLine("\t\t\t{");
		foreach (var stage in stages.Where(s => s.Choices.Count > 0))
		{
			b.AppendLine($"\t\t\t\tcase {Literal(stage.Id)}:");
			foreach (var choice in stage.Choices)
				b.AppendLine($"\t\t\t\t\tchoices.Add(new KeyValuePair<string, string>({Literal(choice.Label)}, {Literal(choice.Next)}));");
			b.AppendLine("\t\t\t\t\tbreak;");
		}
		b.AppendLine("\t\t\t}");
		b.AppendLine();
		b.AppendLine("\t\t\treturn choices;");
		b.AppendLine("\t\t}");
		b.AppendLine();

		// IsObjectiveDone
		b.AppendLine("\t\tpublic static bool IsObjectiveDone(PlayerEntity player, string stage)");
		b.AppendLine("\t\t{");
		b.AppendLine("\t\t\tswitch (stage)");
		b.AppendLine("\t\t\t{");
		foreach (var stage in stages)
		{
			switch (stage.Kind)
			{
				case QuestStageKind.Kill:
					b.AppendLine($"\t\t\t\tcase {Literal(stage.Id)}: return GetProgress(player) >= {stage.Count};");
					break;
				case QuestStageKind.Collect:
					b.AppendLine($"\t\t\t\tcase {Literal(stage.Id)}: return CountCarried<{stage.Target}>(player) >= {stage.Count};");
					break;
				case QuestStageKind.Escort:
					b.AppendLine($"\t\t\t\tcase {Literal(stage.Id)}: return GetProgress(player) >= 1;");
					break;
			}
		}
		b.AppendLine("\t\t\t\tdefault: return true;");
		b.AppendLine("\t\t\t}");
		b.AppendLine("\t\t}");
		b.AppendLine();

		// Choose
		b.AppendLine("\t\t/// <summary>Turns in the current stage (taking collected items and giving its rewards) and moves to the chosen stage.</summary>");
		b.AppendLine("\t\tpublic static void Choose(PlayerEntity player, MobileEntity giver, string next)");
		b.AppendLine("\t\t{");
		b.AppendLine("\t\t\tvar stage = GetStage(player);");
		b.AppendLine();
		b.AppendLine("\t\t\t/* the menu may be stale, so check the choice is still on offer */");
		b.AppendLine("\t\t\tif (!GetChoices(player).Any(c => c.Value == next))");
		b.AppendLine("\t\t\t\treturn;");
		b.AppendLine();
		b.AppendLine("\t\t\tswitch (stage)");
		b.AppendLine("\t\t\t{");
		foreach (var stage in stages.Where(s => s.Kind == QuestStageKind.Collect && s.Consume))
		{
			b.AppendLine($"\t\t\t\tcase {Literal(stage.Id)}:");
			b.AppendLine($"\t\t\t\t\tif (!TakeCarried<{stage.Target}>(player, {stage.Count}))");
			b.AppendLine("\t\t\t\t\t\treturn;");
			b.AppendLine("\t\t\t\t\tbreak;");
		}
		b.AppendLine("\t\t\t}");
		b.AppendLine();
		b.AppendLine("\t\t\tif (stage != NotStarted && stage != Completed)");
		b.AppendLine("\t\t\t\tGiveRewards(player, stage);");
		b.AppendLine();
		b.AppendLine("\t\t\tEnter(player, giver, next);");
		b.AppendLine("\t\t}");
		b.AppendLine();

		// Enter
		b.AppendLine("\t\tprivate static void Enter(PlayerEntity player, MobileEntity giver, string stage)");
		b.AppendLine("\t\t{");
		b.AppendLine("\t\t\tSetStage(player, stage);");
		b.AppendLine("\t\t\tSetProgress(player, 0);");
		b.AppendLine();
		b.AppendLine("\t\t\tgiver.SayTo(player, GetText(stage));");
		b.AppendLine();
		b.AppendLine("\t\t\tswitch (stage)");
		b.AppendLine("\t\t\t{");
		foreach (var stage in stages.Where(s => s.Kind is QuestStageKind.End or QuestStageKind.Escort))
		{
			b.AppendLine($"\t\t\t\tcase {Literal(stage.Id)}:");

			if (stage.Kind == QuestStageKind.End)
			{
				b.AppendLine("\t\t\t\t\tGiveRewards(player, stage);");
				b.AppendLine("\t\t\t\t\tSetStage(player, Completed);");
				b.AppendLine("\t\t\t\t\tplayer.SendMessage(Color.Gold, $\"Quest complete: {Title}\");");
			}
			else
			{
				b.AppendLine("\t\t\t\t\tSummonEscort(player, giver, stage);");
			}

			b.AppendLine("\t\t\t\t\tbreak;");
		}
		b.AppendLine("\t\t\t}");
		b.AppendLine("\t\t}");
		b.AppendLine();

		// GiveRewards
		b.AppendLine("\t\tprivate static void GiveRewards(PlayerEntity player, string stage)");
		b.AppendLine("\t\t{");
		b.AppendLine("\t\t\tswitch (stage)");
		b.AppendLine("\t\t\t{");
		foreach (var stage in stages.Where(HasRewards))
		{
			b.AppendLine($"\t\t\t\tcase {Literal(stage.Id)}:");

			if (stage.RewardExperience > 0)
				b.AppendLine($"\t\t\t\t\tplayer.AwardExperience({stage.RewardExperience}, false);");

			if (stage.RewardGold > 0)
				b.AppendLine($"\t\t\t\t\tnew Gold({stage.RewardGold}).Move(player.Location, true, player.Segment);");

			foreach (var item in RewardItems(stage))
				b.AppendLine($"\t\t\t\t\t{item}.Move(player.Location, true, player.Segment);");

			b.AppendLine("\t\t\t\t\tbreak;");
		}
		b.AppendLine("\t\t\t}");
		b.AppendLine("\t\t}");
		b.AppendLine();

		// OnKilled
		var kills = stages.Where(s => s.Kind == QuestStageKind.Kill).ToList();

		b.AppendLine("\t\t/// <summary>Counts a kill for every player nearby. Called from the target entity's OnDeath script.</summary>");
		b.AppendLine("\t\tpublic static void OnKilled(string entity, MobileEntity source, MobileEntity killer)");
		b.AppendLine("\t\t{");
		b.AppendLine("\t\t\tif (source is null)");
		b.AppendLine("\t\t\t\treturn;");
		b.AppendLine();
		b.AppendLine("\t\t\tvar players = source.GetBeholdersInLOS(3).OfType<PlayerGroup>().SelectMany(g => g.Members).OfType<PlayerEntity>().ToList();");
		b.AppendLine();
		b.AppendLine("\t\t\tif (killer is PlayerEntity playerKiller && !players.Contains(playerKiller))");
		b.AppendLine("\t\t\t\tplayers.Add(playerKiller);");
		b.AppendLine();
		b.AppendLine("\t\t\tforeach (var player in players)");
		b.AppendLine("\t\t\t{");
		b.AppendLine("\t\t\t\tvar stage = GetStage(player);");
		b.AppendLine("\t\t\t\tvar needed = 0;");
		b.AppendLine();
		b.AppendLine("\t\t\t\tswitch (stage)");
		b.AppendLine("\t\t\t\t{");
		foreach (var stage in kills)
			b.AppendLine($"\t\t\t\t\tcase {Literal(stage.Id)}: if (entity == {Literal(stage.Target)}) needed = {stage.Count}; break;");
		b.AppendLine("\t\t\t\t}");
		b.AppendLine();
		b.AppendLine("\t\t\t\tvar progress = GetProgress(player);");
		b.AppendLine();
		b.AppendLine("\t\t\t\tif (progress >= needed)");
		b.AppendLine("\t\t\t\t\tcontinue;");
		b.AppendLine();
		b.AppendLine("\t\t\t\tSetProgress(player, ++progress);");
		b.AppendLine("\t\t\t\tplayer.SendMessage(Color.Yellow, $\"{Title}: {progress}/{needed} {entity}.\");");
		b.AppendLine();
		b.AppendLine("\t\t\t\tif (progress >= needed)");
		b.AppendLine($"\t\t\t\t\tplayer.SendMessage(Color.Yellow, {Literal($"{quest.Title}: done! Return to {quest.GiverName}.")});");
		b.AppendLine("\t\t\t}");
		b.AppendLine("\t\t}");
		b.AppendLine();

		// Escort helpers
		var escorts = stages.Where(s => s.Kind == QuestStageKind.Escort).ToList();

		if (escorts.Count > 0)
		{
			b.AppendLine("\t\tprivate static void SummonEscort(PlayerEntity player, MobileEntity giver, string stage)");
			b.AppendLine("\t\t{");
			b.AppendLine($"\t\t\tif (World.Mobiles.Values.OfType<{q}Escort>().Any(e => e.IsAlive && e.QuestOwner == player && e.QuestStage == stage))");
			b.AppendLine("\t\t\t\treturn;");
			b.AppendLine();
			b.AppendLine($"\t\t\t{q}Escort escort;");
			b.AppendLine();
			b.AppendLine("\t\t\tswitch (stage)");
			b.AppendLine("\t\t\t{");
			foreach (var stage in escorts)
			{
				b.AppendLine($"\t\t\t\tcase {Literal(stage.Id)}:");
				b.AppendLine($"\t\t\t\t\tescort = new {q}Escort(player, stage, {Literal(stage.EscortName)}, {stage.EscortBody}, {stage.EscortHealth}, new Point2D({stage.DestinationX}, {stage.DestinationY}, {stage.DestinationRegion}), {stage.DestinationRange});");
				b.AppendLine("\t\t\t\t\tbreak;");
			}
			b.AppendLine("\t\t\t\tdefault:");
			b.AppendLine("\t\t\t\t\treturn;");
			b.AppendLine("\t\t\t}");
			b.AppendLine();
			b.AppendLine("\t\t\tCreatureGroup.Instantiate(escort, giver.Facet, giver.Segment, giver.Location);");
			b.AppendLine("\t\t\tplayer.SendMessage(Color.Yellow, $\"Order {escort.Name} to follow you, then lead them to safety.\");");
			b.AppendLine("\t\t}");
			b.AppendLine();
			b.AppendLine("\t\tinternal static void OnEscortArrived(PlayerEntity player, string stage)");
			b.AppendLine("\t\t{");
			b.AppendLine("\t\t\tif (player is null || GetStage(player) != stage)");
			b.AppendLine("\t\t\t\treturn;");
			b.AppendLine();
			b.AppendLine("\t\t\tSetProgress(player, 1);");
			b.AppendLine($"\t\t\tplayer.SendMessage(Color.Yellow, {Literal($"{quest.Title}: done! Return to {quest.GiverName}.")});");
			b.AppendLine("\t\t}");
		}
		else
		{
			b.AppendLine("\t\tprivate static void SummonEscort(PlayerEntity player, MobileEntity giver, string stage)");
			b.AppendLine("\t\t{");
			b.AppendLine("\t\t}");
		}

		// Carried items, only when the quest collects anything
		if (stages.Any(s => s.Kind == QuestStageKind.Collect))
		{
			b.AppendLine();
			b.AppendLine("\t\tprivate static List<T> GetCarried<T>(PlayerEntity player) where T : ItemEntity");
			b.AppendLine("\t\t{");
			b.AppendLine("\t\t\tvar items = new List<T>();");
			b.AppendLine();
			b.AppendLine("\t\t\tif (player.Backpack != null) items.AddRange(player.Backpack.Items.OfType<T>());");
			b.AppendLine("\t\t\tif (player.Belt != null) items.AddRange(player.Belt.Items.OfType<T>());");
			b.AppendLine("\t\t\tif (player.RightHand is T right) items.Add(right);");
			b.AppendLine("\t\t\tif (player.LeftHand is T left) items.Add(left);");
			b.AppendLine();
			b.AppendLine("\t\t\treturn items;");
			b.AppendLine("\t\t}");
			b.AppendLine();
			b.AppendLine("\t\tprivate static int CountCarried<T>(PlayerEntity player) where T : ItemEntity");
			b.AppendLine("\t\t\t=> GetCarried<T>(player).Sum(i => (int)Math.Max(1u, i.Amount));");
			b.AppendLine();
			b.AppendLine("\t\tprivate static bool TakeCarried<T>(PlayerEntity player, int count) where T : ItemEntity");
			b.AppendLine("\t\t\t=> player.ConsumeFromCollection(GetCarried<T>(player), (uint)count);");
		}
		else
		{
			b.AppendLine();
			b.AppendLine("\t\tprivate static int CountCarried<T>(PlayerEntity player) => 0;");
		}

		b.AppendLine("\t}");
	}

	private static void GenerateGiver(StringBuilder b, QuestDefinition quest)
	{
		var q = quest.Name;

		b.AppendLine($"\t/// <summary>{Xml(quest.GiverName)}, who gives out {Xml(quest.Title)}. Spawn it from an entity whose OnSpawn returns <c>new {q}QuestGiver()</c>.</summary>");
		b.AppendLine($"\tpublic class {q}QuestGiver : Questkeeper");
		b.AppendLine("\t{");
		b.AppendLine($"\t\tpublic {q}QuestGiver()");
		b.AppendLine("\t\t{");
		b.AppendLine($"\t\t\tName = {Literal(quest.GiverName)};");
		b.AppendLine($"\t\t\tBody = {quest.GiverBody};");
		b.AppendLine();
		b.AppendLine("\t\t\tHealth = MaxHealth = 100;");
		b.AppendLine("\t\t\tBaseDodge = 10;");
		b.AppendLine("\t\t\tIsInvulnerable = true;");
		b.AppendLine("\t\t\tAlignment = Alignment.Lawful;");
		b.AppendLine();
		b.AppendLine("\t\t\tBrain = new IdleAI(this);");
		b.AppendLine("\t\t}");
		b.AppendLine();
		b.AppendLine($"\t\tpublic {q}QuestGiver(Serial serial) : base(serial)");
		b.AppendLine("\t\t{");
		b.AppendLine("\t\t}");
		b.AppendLine();
		b.AppendLine("\t\tpublic override void GetInteractions(PlayerEntity source, List<InteractionEntry> entries)");
		b.AppendLine("\t\t{");
		b.AppendLine($"\t\t\tentries.Add(new QuestEntry(\"Talk\", (player, giver) => {q}Quest.Talk(player, giver)));");
		b.AppendLine();
		b.AppendLine($"\t\t\tforeach (var choice in {q}Quest.GetChoices(source))");
		b.AppendLine("\t\t\t{");
		b.AppendLine("\t\t\t\tvar next = choice.Value;");
		b.AppendLine($"\t\t\t\tentries.Add(new QuestEntry(choice.Key, (player, giver) => {q}Quest.Choose(player, giver, next)));");
		b.AppendLine("\t\t\t}");
		b.AppendLine();
		b.AppendLine("\t\t\tentries.Add(InteractionSeparator.Instance);");
		b.AppendLine();
		b.AppendLine("\t\t\tbase.GetInteractions(source, entries);");
		b.AppendLine("\t\t}");
