		b.AppendLine("\t\t}");
		b.AppendLine("\t}");
	}

	private static bool HasRewards(QuestStage stage)
		=> stage.RewardExperience > 0 || stage.RewardGold > 0 || RewardItems(stage).Any();

	private static IEnumerable<string> RewardItems(QuestStage stage)
	{
		foreach (var raw in (stage.RewardItems ?? String.Empty).Split(','))
		{
			var item = raw.Trim();

			if (item.Length == 0)
				continue;

			if (item.StartsWith("new ") || item.Contains('('))
				yield return item.StartsWith("new ") ? $"({item})" : $"new {item}";
			else
				yield return $"new {item}()";
		}
	}

	private static string DoneOrDefault(QuestStage stage)
		=> String.IsNullOrWhiteSpace(stage.DoneText) ? "You have done what I asked. Choose how to go on." : stage.DoneText;

	/// <summary>A C# string literal for any text.</summary>
	public static string Literal(string? text) => "\"" + Escape(text) + "\"";

	private static string Escape(string? text) => (text ?? String.Empty)
		.Replace("\\", "\\\\").Replace("\"", "\\\"").Replace("\r", "\\r").Replace("\n", "\\n").Replace("\t", "\\t");

	/// <summary>Text for inside an interpolated string literal.</summary>
	private static string Interpolated(string? text) => Escape(text).Replace("{", "{{").Replace("}", "}}");

	private static string Xml(string? text) => (text ?? String.Empty).Replace("&", "&amp;").Replace("<", "&lt;").Replace(">", "&gt;").Replace("\n", " ");
