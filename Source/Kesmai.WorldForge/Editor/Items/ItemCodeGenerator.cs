#nullable enable

using System;
using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis.CSharp;

namespace Kesmai.WorldForge.Editor.Items;

/// <summary>Turns an <see cref="ItemDefinition"/> into a segment source file holding the item's class.</summary>
public static class ItemCodeGenerator
{
	/// <summary>Problems that would stop the item from compiling or working, in plain words. Empty when it's ready.</summary>
	public static List<string> Validate(ItemDefinition item)
	{
		var problems = new List<string>();

		if (!ItemDefinition.IsIdentifier(item.ClassName))
			problems.Add($"The class name \"{item.ClassName}\" must be letters, digits and underscores, starting with a letter.");

		if (String.IsNullOrWhiteSpace(item.DisplayName))
			problems.Add("Give the item a name players will see.");

		if (item.ItemId <= 0)
			problems.Add("Pick the item's art.");

		if (item.Weight < 0)
			problems.Add("The weight can't be negative.");

		if (item.Hue.Trim().Length > 0 && HueExpression(item.Hue) is null)
			problems.Add($"The hue \"{item.Hue}\" isn't a color name or A,R,G,B numbers from 0 to 255.");

		if (item.Kind == ItemKind.Weapon)
		{
			if (!ItemDefinition.WeaponTypes.Contains(item.WeaponType))
				problems.Add($"Pick a weapon type; \"{item.WeaponType}\" isn't one.");

			if (item.MinimumDamage < 0 || item.MaximumDamage < item.MinimumDamage)
				problems.Add("The maximum damage must be at least the minimum damage, and neither below 0.");
		}

		return problems;
	}

	/// <summary><c>Color.Red</c> for a color name, <c>Color.FromArgb(a, r, g, b)</c> for numbers, null when it is neither.</summary>
	public static string? HueExpression(string hue)
	{
		var text = hue.Trim();

		if (text.Length == 0)
			return null;

		var parts = text.Split(',').Select(p => p.Trim()).ToArray();

		if (parts.Length is 3 or 4 && parts.All(p => Byte.TryParse(p, NumberStyles.Integer, CultureInfo.InvariantCulture, out _)))
			return parts.Length == 4 ? $"Color.FromArgb({String.Join(", ", parts)})" : $"Color.FromArgb(255, {String.Join(", ", parts)})";

		return System.Drawing.Color.FromName(text).IsKnownColor ? $"Color.{System.Drawing.Color.FromName(text).Name}" : null;
	}

	private static string Literal(string text) => SymbolDisplay.FormatLiteral(text, quote: true);

	private static readonly string[] _usings =
	[
		"System", "System.Collections.Generic", "System.Drawing", "System.Linq", "DotNext.Buffers", "Kesmai.Server.Game",
		"Kesmai.Server.Items", "Kesmai.Server.Miscellaneous", "Kesmai.Server.Network",
	];

	public static string Generate(ItemDefinition item, string segmentName)
	{
		var b = new StringBuilder();
		var c = item.ClassName;
		var weapon = item.Kind == ItemKind.Weapon;
		var baseClass = weapon ? item.WeaponType : "ItemEntity";

		b.AppendLine("// <auto-generated>");
		b.AppendLine($"// Made with the WorldForge {(weapon ? "Weapon" : "Item")} Maker. Edit it there: saving it again replaces this file.");
		b.AppendLine("// </auto-generated>");
		b.AppendLine(item.ToMarkerLine());
		b.AppendLine();

		foreach (var name in _usings)
			b.AppendLine($"using {name};");

		b.AppendLine("using SpanReader = DotNext.Buffers.SpanReader<byte>;");
		b.AppendLine("using SpanWriter = DotNext.Buffers.PoolingArrayBufferWriter<byte>;");
		b.AppendLine();
		b.AppendLine($"namespace Kesmai.Server.Internal.{segmentName};");
		b.AppendLine();
		b.AppendLine("public partial class Cache");
		b.AppendLine("{");
		b.AppendLine($"\t/// <summary>{System.Security.SecurityElement.Escape(item.DisplayName)}. Create it with new {c}().</summary>");
		b.AppendLine($"\tpublic class {c} : {baseClass}");
		b.AppendLine("\t{");

		if (item.LabelNumber > 0)
			b.AppendLine($"\t\tpublic override int LabelNumber => {item.LabelNumber};");

		b.AppendLine($"\t\tpublic override uint BasePrice => {item.Price};");
		b.AppendLine($"\t\tpublic override int Weight => {item.Weight};");
		b.AppendLine($"\t\tpublic override int Category => {item.Category};");

		if (item.CanBind)
			b.AppendLine("\t\tpublic override bool CanBind => true;");

		if (weapon)
		{
			b.AppendLine();

			if (ItemDefinition.AlternateArtMember(item.WeaponType) is string alternate)
				b.AppendLine($"\t\t{alternate} => {(item.AlternateItemId > 0 ? item.AlternateItemId : item.ItemId)};");

			if (item.Skill.Trim().Length > 0)
				b.AppendLine($"\t\tpublic override Skill Skill => Skill.{item.Skill.Trim()};");

			b.AppendLine($"\t\tpublic override int MinimumDamage => {item.MinimumDamage};");
			b.AppendLine($"\t\tpublic override int MaximumDamage => {item.MaximumDamage};");
			b.AppendLine($"\t\tpublic override int BaseAttackBonus => {item.AttackBonus};");
			b.AppendLine($"\t\tpublic override int BaseArmorBonus => {item.ArmorBonus};");

			if (item.Penetration.Trim().Length > 0)
				b.AppendLine($"\t\tpublic override ShieldPenetration Penetration => ShieldPenetration.{item.Penetration.Trim()};");

			var flags = item.Flags.Where(f => f.IsChecked == true).Select(f => "WeaponFlags." + f.Name).ToList();

			if (flags.Count > 0)
				b.AppendLine($"\t\tpublic override WeaponFlags Flags => {String.Join(" | ", flags)};");
		}

		// constructors: the art id goes to the base class; the Serial one is how the server loads a saved item
		b.AppendLine();
		b.AppendLine($"\t\tpublic {c}() : base({item.ItemId})");
		b.AppendLine("\t\t{");

		if (HueExpression(item.Hue) is string hue)
			b.AppendLine($"\t\t\tHue = {hue};");

		b.AppendLine("\t\t}");
		b.AppendLine();
		b.AppendLine($"\t\tpublic {c}(Serial serial) : base(serial)");
		b.AppendLine("\t\t{");
		b.AppendLine("\t\t}");

		if (item.Description.Trim().Length > 0 || item.IdentifiedDescription.Trim().Length > 0)
		{
			b.AppendLine();
			b.AppendLine("\t\tpublic override void GetDescription(List<LocalizationEntry> entries)");
			b.AppendLine("\t\t{");

			if (item.Description.Trim().Length > 0)
				b.AppendLine($"\t\t\tentries.Add(new LocalizationEntry({Literal(item.Description.Trim())}));");

			if (item.IdentifiedDescription.Trim().Length > 0)
			{
				b.AppendLine();
				b.AppendLine("\t\t\tif (Identified)");
				b.AppendLine($"\t\t\t\tentries.Add(new LocalizationEntry({Literal(item.IdentifiedDescription.Trim())}));");
			}

			b.AppendLine("\t\t}");
		}

		if (item.RequiredLevel > 0 || item.RequiredProfession.Trim().Length > 0)
		{
			b.AppendLine();
			b.AppendLine("\t\tpublic override ItemUseResult ValidateUse(MobileEntity entity)");
			b.AppendLine("\t\t{");
			b.AppendLine("\t\t\tvar result = base.ValidateUse(entity);");
			b.AppendLine();
			b.AppendLine("\t\t\tif (!result.IsAllowed || entity is not PlayerEntity player)");
			b.AppendLine("\t\t\t\treturn result;");

			if (item.RequiredLevel > 0)
			{
				b.AppendLine();
				b.AppendLine($"\t\t\tif (player.Level < {item.RequiredLevel})");
				b.AppendLine("\t\t\t\treturn ItemUseResult.Denied();");
			}

			if (item.RequiredProfession.Trim().Length > 0)
			{
				b.AppendLine();
				b.AppendLine($"\t\t\tif (player.Profession != Profession.{item.RequiredProfession.Trim()})");
				b.AppendLine("\t\t\t\treturn ItemUseResult.Denied();");
			}

			b.AppendLine();
			b.AppendLine("\t\t\treturn result;");
			b.AppendLine("\t\t}");
		}

		// a version number now leaves room to save more about the item later
		b.AppendLine();
		b.AppendLine("\t\tpublic override void Serialize(SpanWriter writer)");
		b.AppendLine("\t\t{");
		b.AppendLine("\t\t\tbase.Serialize(writer);");
		b.AppendLine();
		b.AppendLine("\t\t\twriter.Write((short)1); /* version */");
		b.AppendLine("\t\t}");
		b.AppendLine();
		b.AppendLine("\t\tpublic override void Deserialize(ref SpanReader reader)");
		b.AppendLine("\t\t{");
		b.AppendLine("\t\t\tbase.Deserialize(ref reader);");
		b.AppendLine();
		b.AppendLine("\t\t\tvar version = reader.ReadInt16();");
		b.AppendLine("\t\t}");
		b.AppendLine("\t}");
		b.AppendLine("}");

		return b.ToString();
	}
}
